const stageDefinitions = Object.freeze(Object.fromEntries(stageSpecs.map((spec, order) => {
  const definition = {
    kind: "production",
    requiresApproval: spec.kind === "gate",
    requiresAdapter: false,
    manualChecks: [],
    ...spec,
    order,
    previousStage: PROMO_STAGES[order - 1] ?? null,
    nextStage: PROMO_STAGES[order + 1] ?? null,
  };
  definition.contract = Object.freeze({
    label: definition.label,
    objective: definition.objective,
    inputStages: Object.freeze([...(definition.inputStages ?? [])]),
    outputArtifacts: Object.freeze([...definition.artifacts]),
    executor: definition.executor,
    validation: Object.freeze([...(definition.validation ?? [])]),
    manualChecks: Object.freeze([...(definition.manualChecks ?? [])]),
    fallbackStage: definition.fallbackStage,
    nextStage: definition.nextStage,
  });
  return [definition.stage, Object.freeze(definition)];
})));

